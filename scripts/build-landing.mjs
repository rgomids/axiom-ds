import { cp, mkdir, readFile, writeFile, rm } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { loadTokens, compileTokens } from './tokens.mjs';

// Sources are kept out of generated directories. The product consumes this bundle.
const base = 'packages/landing';
const out = base + '/dist';
await mkdir(out + '/assets', { recursive: true });
for (const retired of ['organic-workflow.css', 'organic-workflow.js']) {
  await rm(out + '/' + retired, { force: true });
  await rm('apps/storybook/public/landing/' + retired, { force: true });
}
let html = await readFile(base + '/src/index.html', 'utf8');
const sections = [...html.matchAll(/\{\{([\w-]+)\}\}/g)].map((match) => match[1]);
for (const name of sections) {
  html = html.replace(
    '{{' + name + '}}',
    await readFile(base + '/src/sections/' + name + '.html', 'utf8'),
  );
}
await writeFile(out + '/index.html', '<!-- Generated by npm run build:landing. -->\n' + html);
for (const file of [
  'preview.js',
  'style.css',
  'app.js',
  'storytelling.css',
  'storytelling.js',
  'story-state.js',
]) {
  await cp(base + '/src/' + file, out + '/' + file);
}
const all = await loadTokens();
const marketing = Object.fromEntries(
  Object.entries(all).filter(([key]) => key.startsWith('semantic.marketing.')),
);
await writeFile(
  out + '/tokens.css',
  '/* Generated from marketing.tokens.json. */\n' + compileTokens(marketing, {}, ':root', ':root'),
);
await cp(base + '/assets', out + '/assets', { recursive: true });
await cp('packages/brand/raster/axiom-mascot-source.png', out + '/assets/axiom-logo.png');
await cp('LICENSE', out + '/LICENSE.txt');
await writeFile(out + '/.nojekyll', '');
const logo = await readFile('packages/brand/raster/axiom-mascot-source.png');
await writeFile(
  out + '/NOTICE.txt',
  'Axiom landing page — Apache-2.0.\nManrope — SIL Open Font License 1.1 (assets/Manrope-OFL.txt).\nOriginal Axiom mascot preserved, SHA256: ' +
    createHash('sha256').update(logo).digest('hex') +
    '\n',
);
await cp(out, 'apps/storybook/public/landing', { recursive: true });
console.log('Built portable Axiom landing with ' + sections.length + ' reusable sections.');
