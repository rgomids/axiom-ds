import { cp, mkdir, readFile, writeFile, rm } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { loadTokens, compileTokens } from './tokens.mjs';
import { renderStorytelling } from '../packages/landing/src/story-markup.mjs';
import { footerMarkup } from '../packages/landing/src/footer-view.mjs';
import { totalUnits } from '../packages/landing/src/orchestration-timeline.mjs';

// Sources are kept out of generated directories. The product consumes this bundle.
const base = 'packages/landing';
const out = base + '/dist';
await mkdir(out + '/assets', { recursive: true });
for (const retired of ['organic-workflow.css', 'organic-workflow.js']) {
  await rm(out + '/' + retired, { force: true });
  await rm('apps/storybook/public/landing/' + retired, { force: true });
}
let html = await readFile(base + '/src/index.html', 'utf8');
const sections = [...html.matchAll(/\{\{([\w-]+)\}\}/g)].map((match) => match[1]);
const storyboardContent = renderStorytelling();
const footerContent = footerMarkup(
  JSON.parse(await readFile(base + '/src/footer.links.json', 'utf8')),
);
const canonicalSource = async (file) =>
  (await readFile(base + '/src/' + file, 'utf8')).replaceAll('\r\n', '\n');
const runtimeFiles = [
  'preview.js',
  'style.css',
  'app.js',
  'storytelling.css',
  'storytelling.js',
  'story-state.js',
  'storyboard-state.js',
  'story-frames.js',
  'effects.css',
  'orchestration.css',
  'orchestration.mjs',
  'orchestration-timeline.mjs',
  'continuity.mjs',
  'chapter-navigation.css',
  'chapter-navigation.mjs',
  'footer.css',
  'footer.mjs',
];
const hash = createHash('sha256').update(storyboardContent).update(footerContent);
for (const file of runtimeFiles) hash.update(await canonicalSource(file));
const revision = hash.digest('hex').slice(0, 12);
html = html.replace(/((?:src|href)=")([^"/]+\.(?:js|css))(")/g, `$1$2?v=${revision}$3`);
for (const name of sections) {
  html = html.replace(
    '{{' + name + '}}',
    (await readFile(base + '/src/sections/' + name + '.html', 'utf8'))
      .replace('<!-- STORYBOARD_CONTENT -->', storyboardContent)
      .replace('<!-- FOOTER_CONTENT -->', footerContent),
  );
}
await writeFile(
  out + '/index.html',
  '<!-- Generated by npm run build:landing. -->\n' + html.replace(/[ \t]+$/gm, ''),
);
for (const file of runtimeFiles) {
  if (/\.m?js$/.test(file)) {
    const source = await readFile(base + '/src/' + file, 'utf8');
    await writeFile(
      out + '/' + file,
      source.replace(/((?:from\s+|import\s*)['"]\.\/[^'"]+\.m?js)(['"])/g, `$1?v=${revision}$2`),
    );
  } else if (file === 'orchestration.css') {
    await writeFile(
      out + '/' + file,
      `.storytelling { --orch-story-units: ${totalUnits}; }\n` + (await canonicalSource(file)),
    );
  } else await cp(base + '/src/' + file, out + '/' + file);
}
const all = await loadTokens();
const marketing = Object.fromEntries(
  Object.entries(all).filter(([key]) => key.startsWith('semantic.marketing.')),
);
await writeFile(
  out + '/tokens.css',
  '/* Generated from marketing.tokens.json. */\n' + compileTokens(marketing, {}, ':root', ':root'),
);
await cp(base + '/assets', out + '/assets', { recursive: true });
await cp('packages/brand/raster/axiom-mascot-source.png', out + '/assets/axiom-logo.png');
await cp('LICENSE', out + '/LICENSE.txt');
await writeFile(out + '/.nojekyll', '');
const logo = await readFile('packages/brand/raster/axiom-mascot-source.png');
await writeFile(
  out + '/NOTICE.txt',
  'Axiom landing page — Apache-2.0.\nManrope — SIL Open Font License 1.1 (assets/Manrope-OFL.txt).\nOriginal Axiom mascot preserved, SHA256: ' +
    createHash('sha256').update(logo).digest('hex') +
    '\nOpenAI mark: official white Blossom, https://openai.com/brand/ (trademark, usage terms apply).\nClaude mark: Simple Icons, CC0, https://github.com/simple-icons/simple-icons/blob/develop/icons/claude.svg (Anthropic trademark). Marks identify the Claude and Codex integrations; no endorsement is implied.\n',
);
await cp(out, 'apps/storybook/public/landing', { recursive: true });
console.log('Built portable Axiom landing with ' + sections.length + ' reusable sections.');
